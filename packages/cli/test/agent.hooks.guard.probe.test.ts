type Row = [expected: 'DENY' | 'ALLOW', tool: string, input: Record<string, unknown>, win?: boolean];

function run(rows: Row[]): void {
  it.each(rows.map((r) => [`${r[0]} ${r[1]}${r[3] ? ' [win]' : ''} ${JSON.stringify(r[2])}`, r] as const))('%s', (_label, row) => {
    const [expected, tool, input, win] = row;
    const d = guardDecision({ hook_event_name: 'PreToolUse', cwd: win ? 'C:\\repo' : '/repo', tool_name: tool, tool_input: input }, win ? wctx : ctx);
    expect(d.deny ? 'DENY' : 'ALLOW').toBe(expected);
  });
}

